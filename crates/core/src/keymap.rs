pub fn by_name(name: &str) -> Option<u8> {
    KEYS.iter().find(|(n, _)| n.eq_ignore_ascii_case(name)).map(|&(_, id)| id)
}

pub fn name(id: u8) -> Option<&'static str> {
    KEYS.iter().find(|&&(_, i)| i == id).map(|&(n, _)| n)
}
